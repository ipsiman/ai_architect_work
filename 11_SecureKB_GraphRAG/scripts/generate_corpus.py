def random_date(rng: random.Random, y1: int, m1: int, y2: int, m2: int) -> date:
    start = date(y1, m1, 1).toordinal()
    end = date(y2, m2, 28).toordinal()
    return date.fromordinal(rng.randint(start, end))


def render_markdown(doc: dict) -> str:
    frontmatter = "\n".join([
        "---",
        f"doc_id: {doc['doc_id']}",
        f"title: {json.dumps(doc['title'], ensure_ascii=False)}",
        f"acl: {doc['acl']}",
        f"department: {json.dumps(doc['department'], ensure_ascii=False)}",
        f"doc_type: {doc['doc_type']}",
        f"date: {doc['date']}",
        "---",
    ])
    return f"{frontmatter}\n\n# {doc['title']}\n\n{doc['body']}\n"


def build_entities() -> dict:
    persons = []
    for p in PERSONS:
        surname = p["full_name"].split()[0]
        persons.append({
            "id": p["id"], "full_name": p["full_name"], "short_name": p["short_name"],
            "position": p["position"],
            "aliases": [p["full_name"], p["short_name"], surname],
        })
    projects = [{"id": pr["id"], "name": pr["name"],
                 "aliases": [pr["name"], f"«{pr['name']}»", f"проект «{pr['name']}»"]}
                for pr in PROJECTS]
    departments = [{"id": dp["id"], "name": dp["name"],
                    "aliases": [dp["name"], f"отдел {dp['name']}"]}
                   for dp in DEPARTMENTS]
    return {"persons": persons, "projects": projects, "departments": departments}


def main() -> None:
    rng = random.Random(SEED)
    docs: list[dict] = []

    for i in range(1, N_PUBLIC + 1):
        docs.append(build_public(rng, i))

    # PII распределяем по internal/secret: 8 internal + 7 secret = 15 документов
    pii_internal_idx = set(rng.sample(range(N_PUBLIC + 1, N_PUBLIC + N_INTERNAL + 1), k=8))
    pii_secret_count = 7
    pii_cycle = 0
    for i in range(N_PUBLIC + 1, N_PUBLIC + N_INTERNAL + 1):
        with_pii = i in pii_internal_idx
        pii = PII_POOL[pii_cycle % len(PII_POOL)] if with_pii else None
        if with_pii:
            pii_cycle += 1
        docs.append(build_internal(rng, i, with_pii, pii))

    for k, i in enumerate(range(N_PUBLIC + N_INTERNAL + 1, N_PUBLIC + N_INTERNAL + N_SECRET + 1)):
        fact = SECRET_MARKER_FACTS[k % len(SECRET_MARKER_FACTS)]
        with_pii = k < pii_secret_count
        pii = PII_POOL[(pii_cycle + k) % len(PII_POOL)] if with_pii else None
        docs.append(build_secret(rng, i, fact, with_pii, pii))

    CORPUS_DIR.mkdir(parents=True, exist_ok=True)
    for old in CORPUS_DIR.glob("*.md"):
        old.unlink()
    for doc in docs:
        (CORPUS_DIR / f"{doc['doc_id']}.md").write_text(render_markdown(doc), encoding="utf-8")

    ENTITIES_PATH.parent.mkdir(parents=True, exist_ok=True)
    ENTITIES_PATH.write_text(
        json.dumps(build_entities(), ensure_ascii=False, indent=2), encoding="utf-8")

    by_acl: dict[str, int] = {}
    for doc in docs:
        by_acl[doc["acl"]] = by_acl.get(doc["acl"], 0) + 1
    print(f"Сгенерировано документов: {len(docs)} ({by_acl})")
    print(f"Корпус: {CORPUS_DIR}")
    print(f"Сущности: {ENTITIES_PATH}")


if __name__ == "__main__":
    main()
